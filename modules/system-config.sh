#!/usr/bin/env bash
# =============================================================================
# System Configuration Module (runs inside chroot)
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

configure_system() {
  step "Configuring System"

  load_config

  # Configure hostname
  configure_hostname

  # Configure timezone
  configure_timezone

  # Configure locale
  configure_locale

  # Configure keymap
  configure_keymap

  # Configure fstab
  configure_fstab

  success "System configured"
}

configure_hostname() {
  info "Setting hostname: $HOSTNAME"
  echo "$HOSTNAME" > /etc/hostname || die "Failed to set hostname"

  cat > /etc/hosts << EOF
127.0.0.1     localhost
::1           localhost
127.0.1.1     ${HOSTNAME}.localdomain ${HOSTNAME}
EOF

  record OK "hostname" "$HOSTNAME"
}

configure_timezone() {
  info "Setting timezone: $TIMEZONE"

  ln -sf "/usr/share/zoneinfo/$TIMEZONE" /etc/localtime || \
    die "Failed to set timezone"

  record OK "timezone" "$TIMEZONE"
}

configure_locale() {
  info "Configuring locale..."

  # Generate en_US.UTF-8 and ru_RU.UTF-8
  cat > /etc/locale.gen << 'EOF'
en_US.UTF-8 UTF-8
ru_RU.UTF-8 UTF-8
EOF

  locale-gen || die "Failed to generate locales"

  # Set default locale
  eselect locale set en_US.utf8 || warn "Failed to set default locale"

  # Update environment
  env-update && source /etc/profile

  record OK "locale" "en_US.UTF-8, ru_RU.UTF-8"
}

configure_keymap() {
  info "Setting keymap: $KEYMAP"

  if [[ "$INIT_SYSTEM" == "openrc" ]]; then
    sed -i "s/^keymap=.*/keymap=\"$KEYMAP\"/" /etc/conf.d/keymaps || \
      warn "Failed to set keymap in /etc/conf.d/keymaps"
  else
    echo "KEYMAP=$KEYMAP" > /etc/vconsole.conf || \
      warn "Failed to set keymap in /etc/vconsole.conf"
  fi

  record OK "keymap" "$KEYMAP"
}

configure_fstab() {
  info "Generating /etc/fstab..."

  # Get UUIDs
  local root_uuid
  local efi_uuid
  local swap_uuid

  root_uuid=$(blkid -s UUID -o value "$PROOT" 2>/dev/null)
  [[ -n "$PEFI" ]] && efi_uuid=$(blkid -s UUID -o value "$PEFI" 2>/dev/null)
  [[ -n "$PSWAP" ]] && swap_uuid=$(blkid -s UUID -o value "$PSWAP" 2>/dev/null)

  cat > /etc/fstab << EOF
# /etc/fstab: static file system information
# Generated by gentoo-installer on $(date)

# <fs>                                  <mountpoint>  <type>  <opts>              <dump> <pass>
EOF

  # Root partition
  if [[ -n "$root_uuid" ]]; then
    echo "UUID=$root_uuid  /             $FS_TYPE  defaults,noatime    0 1" >> /etc/fstab
  else
    echo "$PROOT        /             $FS_TYPE  defaults,noatime    0 1" >> /etc/fstab
  fi

  # EFI partition (if UEFI)
  if [[ "$BOOT_TYPE" == "uefi" ]] && [[ -n "$PEFI" ]]; then
    if [[ -n "$efi_uuid" ]]; then
      echo "UUID=$efi_uuid  /boot/efi     vfat      defaults            0 2" >> /etc/fstab
    else
      echo "$PEFI           /boot/efi     vfat      defaults            0 2" >> /etc/fstab
    fi
  fi

  # Swap partition
  if [[ -n "$PSWAP" ]]; then
    if [[ -n "$swap_uuid" ]]; then
      echo "UUID=$swap_uuid  none          swap      sw                  0 0" >> /etc/fstab
    else
      echo "$PSWAP          none          swap      sw                  0 0" >> /etc/fstab
    fi
  fi

  success "/etc/fstab generated"
  record OK "fstab" "configured"
}

# Run if executed directly
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  require_chroot
  configure_system
fi
