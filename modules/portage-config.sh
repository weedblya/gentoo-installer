#!/usr/bin/env bash
# =============================================================================
# Portage Configuration Module
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

configure_portage() {
  step "Configuring Portage"

  load_config

  # Detect CPU cores
  local nproc_count
  nproc_count=$(nproc)
  local makeopts_j=$((nproc_count + 1))

  info "CPU cores: $nproc_count"
  info "MAKEOPTS: -j${makeopts_j}"

  # Configure make.conf
  configure_make_conf "$makeopts_j"

  # Configure repos.conf
  configure_repos_conf

  # Copy DNS info
  copy_resolv_conf

  success "Portage configured"
  record OK "portage configuration" "make.conf, repos.conf"
}

configure_make_conf() {
  local makeopts_j=$1

  info "Configuring /etc/portage/make.conf..."

  # Backup original
  [[ -f "$MNT/etc/portage/make.conf" ]] && \
    cp "$MNT/etc/portage/make.conf" "$MNT/etc/portage/make.conf.bak"

  cat > "$MNT/etc/portage/make.conf" << EOF
# Gentoo make.conf
# Generated by gentoo-installer on $(date)

# Compiler flags
COMMON_FLAGS="-march=native -O2 -pipe"
CFLAGS="\${COMMON_FLAGS}"
CXXFLAGS="\${COMMON_FLAGS}"
FCFLAGS="\${COMMON_FLAGS}"
FFLAGS="\${COMMON_FLAGS}"

# Make options
MAKEOPTS="-j${makeopts_j}"
EMERGE_DEFAULT_OPTS="--jobs=4 --load-average=${nproc_count}"

# Portage features
FEATURES="parallel-fetch parallel-install"

# Video cards
VIDEO_CARDS="${VIDEO_CARDS:-dummy}"

# Accept licenses
ACCEPT_LICENSE="*"

# Language support
L10N="en ru"

# Use flags
USE="elogind -systemd"
EOF

  # Add systemd USE flag if needed
  if [[ "$INIT_SYSTEM" == "systemd" ]]; then
    sed -i 's/USE="elogind -systemd"/USE="systemd -elogind"/' "$MNT/etc/portage/make.conf"
  fi

  # Add NVIDIA-specific configuration
  if ((HAVE_NVIDIA)); then
    cat >> "$MNT/etc/portage/make.conf" << 'EOF'

# NVIDIA configuration
ACCEPT_KEYWORDS="~amd64"
EOF
  fi

  # Add binary host if enabled
  if ((USE_BINHOST)); then
    cat >> "$MNT/etc/portage/make.conf" << 'EOF'

# Binary package host
FEATURES="${FEATURES} getbinpkg"
PORTAGE_BINHOST="https://binpkgs.gentoo.org/x86-64/"
EOF
  fi

  success "make.conf configured"
}

configure_repos_conf() {
  info "Configuring repositories..."

  mkdir -p "$MNT/etc/portage/repos.conf"

  cat > "$MNT/etc/portage/repos.conf/gentoo.conf" << 'EOF'
[DEFAULT]
main-repo = gentoo

[gentoo]
location = /var/db/repos/gentoo
sync-type = rsync
sync-uri = rsync://rsync.gentoo.org/gentoo-portage
auto-sync = yes
sync-rsync-verify-jobs = 1
sync-rsync-verify-metamanifest = yes
sync-rsync-verify-max-age = 24
sync-openpgp-key-path = /usr/share/openpgp-keys/gentoo-release.asc
sync-openpgp-keyserver = hkps://keys.gentoo.org
sync-openpgp-key-refresh-retry-count = 40
sync-openpgp-key-refresh-retry-overall-timeout = 1200
sync-openpgp-key-refresh-retry-delay-exp-base = 2
sync-openpgp-key-refresh-retry-delay-max = 60
sync-openpgp-key-refresh-retry-delay-mult = 4
sync-webrsync-verify-signature = yes
EOF

  success "repos.conf configured"
}

copy_resolv_conf() {
  info "Copying DNS configuration..."
  cp -L /etc/resolv.conf "$MNT/etc/resolv.conf" || \
    warn "Failed to copy resolv.conf"
}

# Run if executed directly
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  require_root
  configure_portage
fi
